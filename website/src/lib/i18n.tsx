export type Lang = 'en' | 'ar'

interface I18n {
  lang: Lang
  dir: 'ltr' | 'rtl'
  t: Strings
  setLang: (lang: Lang) => void
  /** A name in the reader's language, the other when that one is missing. */
  pick: (en: string | undefined, ar: string | undefined) => string
  city: (code: Governorate | undefined) => string
}

const LANG_KEY = 'saba-admin-lang'
const I18nContext = createContext<I18n | null>(null)

/** The admin's language, as kept between visits; http.ts sends it to the server too. */
export function savedLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === 'ar' ? 'ar' : 'en'
  } catch {
    return 'en'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(savedLang)
  const dir = lang === 'ar' ? 'rtl' : 'ltr'

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = dir
  }, [lang, dir])

  const setLang = (next: Lang) => {
    setLangState(next)
    try {
      localStorage.setItem(LANG_KEY, next)
    } catch {
      // Not kept; the choice still holds for this page.
    }
  }

  const value: I18n = {
    lang,
    dir,
    t: lang === 'ar' ? ar : en,
    setLang,
    pick: (enName, arName) => (lang === 'ar' ? arName || enName : enName || arName) ?? '',
    city: (code) => (code ? GOVERNORATES[code][lang === 'ar' ? 1 : 0] : ''),
  }
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n outside I18nProvider')
  return value
}
