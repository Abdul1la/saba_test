export type Lang = 'en' | 'ar'

export const dictionaries: Readonly<Record<Lang, Readonly<Record<string, string>>>> = { en, ar }

/** A value put into a message: the same in both languages, or one per language. */
export type MessageParam = string | number | Readonly<Record<Lang, string>>
export type MessageParams = Readonly<Record<string, MessageParam>>

export function isMessageKey(value: string): value is MessageKey {
  return Object.hasOwn(en, value)
}

/** [key] in [lang], with {placeholders} filled from [params]. */
export function t(lang: Lang, key: MessageKey, params?: MessageParams): string {
  const text = dictionaries[lang][key]
  if (text === undefined) return `⟦${key}⟧`
  return text.replace(/\{(\w+)\}(\.?)/g, (placeholder, name: string, stop: string) => {
    const param = params?.[name]
    if (param === undefined) return placeholder
    const value = typeof param === 'object' ? param[lang] : String(param)
    // A value that ends its own sentence (Saba's "…the case itself.") takes no second stop.
    return stop && /[.!?…؟]$/.test(value) ? value : value + stop
  })
}

/** "A, B and C" in both languages, for a message parameter. */
export function listOf(items: readonly string[]): Readonly<Record<Lang, string>> {
  const join = (separator: string, last: string) =>
    items.length < 2 ? (items[0] ?? '') : `${items.slice(0, -1).join(separator)}${last}${items.at(-1)}`
  return { en: join(', ', ' and '), ar: join('، ', ' و') }
}
